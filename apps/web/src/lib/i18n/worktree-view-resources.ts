export function installWorktreeViewTranslations() {
  if (installed) return;
  installed = true;
  for (const [locale, translation] of Object.entries(worktreeViewTranslations)) {
    i18n.addResourceBundle(locale, "common", { worktreeView: translation }, true, true);
  }
}
